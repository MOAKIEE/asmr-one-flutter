import 'package:flutter/material.dart';

/// 轻量本地化实现：三语（简体中文 / 日本語 / English）字典 + Delegate。
///
/// 不依赖代码生成，便于直接阅读与维护。
class L10n {
  const L10n(this._values);

  final Map<String, String> _values;

  String call(String key, [Map<String, Object?>? params]) {
    var s = _values[key] ?? _zh[key] ?? key;
    if (params != null) {
      params.forEach((k, v) => s = s.replaceAll('{$k}', '${v ?? ''}'));
    }
    return s;
  }

  static const LocalizationsDelegate<L10n> delegate = _L10nDelegate();

  static L10n of(BuildContext context) =>
      Localizations.of<L10n>(context, L10n) ?? const L10n(_zh);

  static const List<Locale> supportedLocales = [
    Locale('zh', 'CN'),
    Locale('ja', 'JP'),
    Locale('en', 'US'),
  ];

  static L10n forLocale(Locale locale) {
    switch (locale.languageCode) {
      case 'ja':
        return const L10n(_ja);
      case 'en':
        return const L10n(_en);
      default:
        return const L10n(_zh);
    }
  }
}

class _L10nDelegate extends LocalizationsDelegate<L10n> {
  const _L10nDelegate();

  @override
  bool isSupported(Locale locale) =>
      ['zh', 'ja', 'en'].contains(locale.languageCode);

  @override
  Future<L10n> load(Locale locale) async => L10n.forLocale(locale);

  @override
  bool shouldReload(_L10nDelegate old) => false;
}

